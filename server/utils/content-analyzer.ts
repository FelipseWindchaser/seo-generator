// /server/utils/content-analyzer.ts

import { z } from "zod";
import { getModel, ModelProvider } from "~/server/services/langchain.service";
import { ChatPromptTemplate } from "@langchain/core/prompts";
import type { GenerationRequest, AnalysisDetail } from "~/types";

const analysisSchema = z.object({
  utpAnalysis: z.array(
    z.object({
      point: z.string(),
      isCovered: z.boolean(),
      evidence: z.string(),
    })
  ),
  painPointAnalysis: z.array(
    z.object({
      point: z.string(),
      isCovered: z.boolean(),
      evidence: z.string(),
    })
  ),
});
type AnalysisResponseType = z.infer<typeof analysisSchema>;

export class ContentAnalyzer {
  async analyze(
    text: string,
    request: GenerationRequest
  ): Promise<AnalysisResponseType> {
    const model = getModel(request.modelProvider || ModelProvider.GEMINI, {
      temperature: 0.0,
    });

    const prompt = ChatPromptTemplate.fromTemplate(`
      Ты — высокоточный ассистент-аналитик. Твоя задача — провести глубокий семантический анализ текста, чтобы определить, раскрыты ли в нем ключевые маркетинговые тезисы. Ты должен понимать не только прямой смысл, но и косвенные связи.

      --- ТЕКСТ ДЛЯ АНАЛИЗА ---
      {text}

      --- СПИСОК УТП (Уникальные Торговые Преимущества) ---
      {usp}

      --- СПИСОК БОЛЕЙ (Проблемы из отзывов, которые нужно отработать) ---
      {reviews}

      --- ТВОЙ ПРОЦЕСС МЫШЛЕНИЯ (Chain-of-Thought) ---
      Прежде чем дать ответ для каждого тезиса, ты должен следовать этой логике:
      1.  Прочитай тезис (например, "боль": "Сломалась через 5 минут").
      2.  Определи его **суть**. В чем заключается фундаментальная проблема или преимущество? (Суть: "проблема низкой надежности, быстрая поломка").
      3.  Прочитай весь текст для анализа. Ищи не точные слова, а **концепции, которые решают эту проблему или подтверждают преимущество**.
      4.  Найди в тексте предложение, которое является **лучшим ответом** на суть тезиса. (Например, предложение о "строгом контроле качества" и "гарантии" — это прямой ответ на проблему "низкой надежности").
      5.  Если такое предложение найдено, вынеси вердикт isCovered: true и приведи его как evidence. Если нет — isCovered: false.

      --- ПРАВИЛА ВЫВОДА ---
      - isCovered: true, если СМЫСЛ тезиса передан в тексте. Ищи **решение проблемы**, а не просто упоминание.
      - isCovered: false, если тезис в тексте не упоминается и его суть не раскрыта.
      - evidence: Если isCovered: true, приведи ТОЧНУЮ цитату (одно полное предложение) из текста, которое лучше всего доказывает раскрытие тезиса. Если false, оставь пустую строку.

      --- ПРИМЕРЫ ПРАВИЛЬНОГО АНАЛИЗА ---
      Пример 1 (Прямое опровержение "боли"):
      - Тезис ("боль"): "Очень шумная"
      - Предложение в тексте: "Благодаря инверторному мотору нового поколения, устройство работает практически бесшумно."
      - Твой вывод: {{ "point": "Очень шумная", "isCovered": true, "evidence": "Благодаря инверторному мотору нового поколения, устройство работает практически бесшумно." }}

      Пример 2 (Несоответствие):
      - Тезис (УТП): "Подходит для твердых овощей"
      - Предложение в тексте: "Наш прибор отлично справляется с яблоками и апельсинами."
      - Твой вывод: {{ "point": "Подходит для твердых овощей", "isCovered": false, "evidence": "" }}

      **Пример 3 (НОВЫЙ, КЛЮЧЕВОЙ ПРИМЕР - Косвенное решение "боли" через концепцию):**
      - Тезис ("боль"): "Сломалась через 5 минут после включения"
      - Предложение в тексте: "В отличие от аналогов, соковыжималка PowerTwist J7 отличается повышенной надежностью и долговечностью, благодаря использованию высококачественных материалов и строгой системе контроля качества."
      - *Твои рассуждения (внутренние):*
          - *Суть "боли":* Товар ненадежный, быстро ломается.
          - *Поиск решения в тексте:* Есть ли в тексте что-то про надежность? Да, есть предложение про "повышенную надежность", "долговечность" и "контроль качества".
          - *Вывод:* Это предложение напрямую решает проблему ненадежности. Значит, "боль" отработана.
      - Твой финальный вывод: {{ "point": "Сломалась через 5 минут после включения", "isCovered": true, "evidence": "В отличие от аналогов, соковыжималка PowerTwist J7 отличается повышенной надежностью и долговечностью, благодаря использованию высококачественных материалов и строгой системе контроля качества." }}

      КРИТИЧЕСКИ ВАЖНО: Верни ответ ТОЛЬКО в формате JSON, соответствующем схеме. Не включай в JSON свои рассуждения.
    `);

    const chain = prompt.pipe(model.withStructuredOutput(analysisSchema));
    const response = (await chain.invoke({
      text: text,
      usp: JSON.stringify(request.usp),
      reviews: request.reviews,
    })) as AnalysisResponseType;
    return response;
  }
}